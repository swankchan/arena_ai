// Static, lightweight map derived from the same OSM road/coastline data used by the in-game atlas.
import { writeFileSync } from 'node:fs';
import { HK_FULL_ROADS } from '../../js/hk-full-roads-data.js';
import { HK_FULL_MAP } from '../../js/hk-full-map-data.js';

// A north-up Victoria Harbour crop in the game's metre coordinate system.
const bounds = { minX: -5500, maxX: 8700, minZ: -8500, maxZ: 840 };
const width = 380, height = 250;
const x = (v) => ((v - bounds.minX) * width / (bounds.maxX - bounds.minX)).toFixed(1);
const y = (v) => ((v - bounds.minZ) * height / (bounds.maxZ - bounds.minZ)).toFixed(1);
function intersects(flat) {
  let minX = Infinity, maxX = -Infinity, minZ = Infinity, maxZ = -Infinity;
  for (let i = 0; i + 1 < flat.length; i += 2) {
    minX = Math.min(minX, flat[i]); maxX = Math.max(maxX, flat[i]);
    minZ = Math.min(minZ, flat[i + 1]); maxZ = Math.max(maxZ, flat[i + 1]);
  }
  return maxX >= bounds.minX && minX <= bounds.maxX && maxZ >= bounds.minZ && minZ <= bounds.maxZ;
}
function path(flat, close = false) {
  let d = `M${x(flat[0])} ${y(flat[1])}`;
  for (let i = 2; i + 1 < flat.length; i += 2) d += `L${x(flat[i])} ${y(flat[i + 1])}`;
  return d + (close ? 'Z' : '');
}
const land = HK_FULL_MAP.land.filter((r) => r.length >= 6 && intersects(r)).map((r) => path(r, true));
const roads = [[], []];
for (const [, roadWidth, , , flags, flat] of HK_FULL_ROADS.roads) {
  if (!flat || flat.length < 4 || roadWidth < 9 || !intersects(flat)) continue;
  roads[(flags & 1) || roadWidth >= 13 ? 1 : 0].push(path(flat));
}
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}">
<!-- Hong Kong game atlas: © OpenStreetMap contributors, ODbL 1.0. Generated by tools/graphics/build-loading-map.mjs. -->
<defs><clipPath id="frame"><rect width="380" height="250" rx="12"/></clipPath><radialGradient id="sea"><stop stop-color="#142b2e"/><stop offset="1" stop-color="#0b1519"/></radialGradient></defs>
<g clip-path="url(#frame)"><path fill="url(#sea)" d="M0 0h380v250H0z"/>
<g fill="#263331" stroke="#64776d" stroke-width=".55" opacity=".85">${land.map((d) => `<path d="${d}"/>`).join('')}</g>
<path d="${roads[0].join('')}" fill="none" stroke="#7a8c7e" stroke-width=".45" opacity=".66" stroke-linecap="round" stroke-linejoin="round"/>
<path d="${roads[1].join('')}" fill="none" stroke="#dfc577" stroke-width=".85" opacity=".9" stroke-linecap="round" stroke-linejoin="round"/>
<path d="M0 50H380M0 100H380M0 150H380M0 200H380M76 0V250M152 0V250M228 0V250M304 0V250" fill="none" stroke="#d3e1d7" stroke-width=".3" opacity=".12"/>
</g><rect x=".5" y=".5" width="379" height="249" rx="12" fill="none" stroke="#a8c3ab" stroke-opacity=".3"/>
</svg>\n`;
writeFileSync(new URL('../../assets/hong-kong-loading-map.svg', import.meta.url), svg);
console.log(`Map: ${land.length} coastline polygons, ${roads[0].length + roads[1].length} road paths, ${svg.length} bytes`);
