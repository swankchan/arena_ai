#!/usr/bin/env python3
"""Triangulate the provisional loop-grade opening. Requires Shapely and node.
The opening is built from exactly the rectangles used by the runtime terrain clip.
"""
import json,math,pathlib,subprocess
from shapely.geometry import Polygon,box
from shapely.ops import unary_union,triangulate
root=pathlib.Path(__file__).resolve().parents[3]
src="import {loopGradeRects} from './js/cities/hongkong/peak-tram-loop-grading-site.js'; console.log(JSON.stringify(loopGradeRects()));"
rects=json.loads(subprocess.check_output(['node','--input-type=module','-e',src],cwd=root))
def rect(r):
 x,z,u,v,h,w=(r[k] for k in ('cx','cz','ux','uz','hx','hz'))
 return Polygon([(x+u*a-v*b,z+v*a+u*b) for a,b in [(-h,-w),(h,-w),(h,w),(-h,w)]])
area=unary_union([rect(r) for r in rects]);points=[]
minx,minz,maxx,maxz=area.bounds
for x in range(math.floor(minx),math.ceil(maxx)):
 for z in range(math.floor(minz),math.ceil(maxz)):
  part=area.intersection(box(x,z,x+1,z+1))
  if part.is_empty or part.area<1e-9: continue
  for tri in triangulate(part):
   if not part.covers(tri.representative_point()) or abs(tri.intersection(part).area-tri.area)>1e-7:continue
   points.extend([round(c,6) for p in list(tri.exterior.coords)[:3] for c in p])
out='// Generated by tools/cities/hongkong/build-peak-tram-loop-grading.py.\nexport const LOOP_GRADE_TRIANGLES = '+json.dumps(points,separators=(',',':'))+';\n'
(root/'js/cities/hongkong/peak-tram-loop-grading-data.js').write_text(out)
print('area',area.area,'triangles',len(points)//6)
