#!/usr/bin/env python3
"""Triangulate the provisional Central approach grade opening. Requires Shapely and node.
The opening is built from exactly the rectangles used by the runtime terrain clip.
"""
import json,math,pathlib,subprocess
from shapely.geometry import Polygon,box
from shapely import constrained_delaunay_triangles
from shapely.ops import unary_union,triangulate
root=pathlib.Path(__file__).resolve().parents[3]
src="import {centralGradeRects} from './js/cities/hongkong/peak-tram-central-earthworks-site.js'; console.log(JSON.stringify(centralGradeRects()));"
rects=json.loads(subprocess.check_output(['node','--input-type=module','-e',src],cwd=root))
def rect(r):
 x,z,u,v,h,w=(r[k] for k in ('cx','cz','ux','uz','hx','hz'))
 return Polygon([(x+u*a-v*b,z+v*a+u*b) for a,b in [(-h,-w),(h,-w),(h,w),(-h,w)]])
area=unary_union([rect(r) for r in rects]);points=[]
minx,minz,maxx,maxz=area.bounds
for ix in range(math.floor(minx*2),math.ceil(maxx*2)):
 for iz in range(math.floor(minz*2),math.ceil(maxz*2)):
  x,z=ix/2,iz/2
  part=area.intersection(box(x,z,x+.5,z+.5))
  if part.is_empty or part.area<1e-9: continue
  for tri in constrained_delaunay_triangles(part).geoms:
   coords=list(tri.exterior.coords)[:3]
   if (coords[1][0]-coords[0][0])*(coords[2][1]-coords[0][1])-(coords[1][1]-coords[0][1])*(coords[2][0]-coords[0][0])<0: coords[1],coords[2]=coords[2],coords[1]
   points.extend([round(c,6) for p in coords for c in p])
out='// Generated by tools/cities/hongkong/build-peak-tram-central-earthworks.py.\nexport const CENTRAL_GRADE_TRIANGLES = '+json.dumps(points,separators=(',',':'))+';\n'
(root/'js/cities/hongkong/peak-tram-central-earthworks-data.js').write_text(out)
print('area',area.area,'triangles',len(points)//6, 'tri area',sum(Polygon([(points[i],points[i+1]),(points[i+2],points[i+3]),(points[i+4],points[i+5])]).area for i in range(0,len(points),6)))
