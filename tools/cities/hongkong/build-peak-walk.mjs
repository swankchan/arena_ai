import fs from 'node:fs';
import { makeFrame } from '../../geo/frame.mjs';
import config from './config.mjs';

// Exact OSM centerlines, no simplification; the Harlech branch towards Pok Fu Lam is not the circuit.
const source = JSON.parse(fs.readFileSync('tools/data/hongkong/roads_minor_sw.json', 'utf8'));
const { toWorld } = makeFrame(config.frame);
const ways = source.elements.filter(e => ['Lugard Road', 'Harlech Road'].includes(e.tags?.['name:en']) && e.id !== 155738201)
  .map(e => ({id:e.id, name:e.tags['name:en'], bridge:e.tags.bridge === 'yes', points:e.geometry.flatMap(p => toWorld(p.lon,p.lat).map(v => +v.toFixed(3)))}));
if (ways.length !== 14) throw Error(`Expected 14 route ways, got ${ways.length}`);
const output = `// Generated by tools/cities/hongkong/build-peak-walk.mjs from roads_minor_sw.json. © OpenStreetMap contributors, ODbL.\nexport const PEAK_WALK_WAYS = ${JSON.stringify(ways)};\n`;
const path = 'js/cities/hongkong/peak-walk-data.js';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(path, 'utf8') !== output) throw Error('Peak walk data is out of date');
} else fs.writeFileSync(path, output);
