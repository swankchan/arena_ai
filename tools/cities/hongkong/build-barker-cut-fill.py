#!/usr/bin/env python3
"""Triangulate the union of generated Plantation Road opening rectangles on a 1m grid.
Requires shapely. Height is deliberately not baked: runtime samples the current road profile.
"""
import json, math, pathlib, subprocess
from shapely.geometry import Polygon, box
from shapely.geometry.polygon import orient
from shapely.ops import unary_union, triangulate
root=pathlib.Path(__file__).resolve().parents[3]
src="""import {TERRAIN_TUNNEL_OPENING_RECTS as R} from './js/cities/hongkong/road-elevation.js'; console.log(JSON.stringify(R.filter(r=>r.routeId==='osm-tunnel:36109')));"""
rs=json.loads(subprocess.check_output(['node','--input-type=module','-e',src],cwd=root))
polys=[]
for r in rs:
 x,z,u,v,h,w=(r[k] for k in ('cx','cz','ux','uz','hx','hz'))
 polys.append(Polygon([(x+u*a-v*b,z+v*a+u*b) for a,b in [(-h,-w),(h,-w),(h,w),(-h,w)]]))
area=unary_union(polys); assert area.geom_type=='Polygon'
verts=[]
minx,minz,maxx,maxz=area.bounds
for x in range(math.floor(minx),math.ceil(maxx)):
 for z in range(math.floor(minz),math.ceil(maxz)):
  part=area.intersection(box(x,z,x+1,z+1))
  if part.is_empty or part.area<1e-8: continue
  # Delaunay triangles crossing a concave union boundary must be clipped,
  # then triangulated again instead of discarded (which left visible pinholes).
  for tri in triangulate(part):
   clipped=tri.intersection(part)
   pieces=[clipped] if clipped.geom_type=='Polygon' else getattr(clipped,'geoms',[])
   for piece in pieces:
    if piece.geom_type!='Polygon' or piece.area<1e-10: continue
    for small in triangulate(piece):
     if piece.covers(small):
      verts.extend([round(c,6) for p in list(orient(small,sign=1).exterior.coords)[:3] for c in p])

boundary=[[round(x,6),round(z,6)] for x,z in area.exterior.coords]
output='// Generated by tools/cities/hongkong/build-barker-cut-fill.py; union of OSM tunnel opening rectangles.\nexport const BARKER_OPENING_TRIANGLES = '+json.dumps(verts,separators=(',',':'))+';\nexport const BARKER_OPENING_BOUNDARY = '+json.dumps(boundary,separators=(',',':'))+';\n'
(root/'js/cities/hongkong/peak-tram-barker-cut-data.js').write_text(output)
print('triangles',len(verts)//6,'area',area.area)
