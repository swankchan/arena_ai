// Build the territory-wide drivable OSM road layer. This is deliberately separate from the detailed港九 block/building
// pipeline: roads outside that core become real 3D surfaces and spawn/ground-query geometry, not procedurally cut lots.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeFrame } from '../../geo/frame.mjs';
import { buildRoads } from '../../geo/roads.mjs';
import { bbox, rdp } from '../../geo/geom.mjs';

const HERE = fileURLToPath(new URL('.', import.meta.url));
const DEFAULT_DATA = path.resolve(HERE, '../../data/hongkong/full-map-cache');
const DEFAULT_OUT = path.resolve(HERE, '../../../js/hk-full-roads-data.js');
const DEFAULT_MANIFEST = path.resolve(HERE, '../../data/hongkong/full-roads-manifest.json');
const q = (value) => Math.round(value * 10) / 10;
const flat = (points) => points.flatMap(([x, z]) => [q(x), q(z)]);
const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));

function worldBounds(bounds, frame) {
  const corners = [
    [bounds.west, bounds.south], [bounds.east, bounds.south],
    [bounds.west, bounds.north], [bounds.east, bounds.north]
  ].map(([lon, lat]) => frame.toWorld(lon, lat));
  const bb = bbox(corners);
  return { minX: bb.x0, maxX: bb.x1, minZ: bb.z0, maxZ: bb.z1 };
}

function distanceToRoad(points, x, z) {
  let best = Infinity;
  for (let i = 1; i < points.length; i++) {
    const [ax, az] = points[i - 1], [bx, bz] = points[i];
    const dx = bx - ax, dz = bz - az;
    const lengthSq = dx * dx + dz * dz || 1;
    const t = Math.max(0, Math.min(1, ((x - ax) * dx + (z - az) * dz) / lengthSq));
    best = Math.min(best, Math.hypot(ax + dx * t - x, az + dz * t - z));
  }
  return best;
}

export async function buildHongKongFullRoads({ dataDir = DEFAULT_DATA, outFile = DEFAULT_OUT, manifestFile = DEFAULT_MANIFEST } = {}) {
  const { default: cfg } = await import('./config.mjs');
  const frame = makeFrame(cfg.frame);
  const files = ['roads_major.json', 'roads_minor_sw.json', 'roads_minor_se.json', 'roads_minor_nw.json', 'roads_minor_ne.json'];
  const seen = new Set();
  const elements = [];
  let source = null;
  for (const file of files) {
    const json = readJson(path.join(dataDir, file));
    source ||= json.source;
    for (const element of json.elements) {
      const key = `${element.type}/${element.id}`;
      if (seen.has(key)) continue;
      seen.add(key);
      elements.push(element);
    }
  }
  const built = buildRoads(elements, frame.toWorld);
  const drivable = built.roads.filter((road) => road.drivable);
  const roads = drivable.map((road) => {
    const flags = (road.highway ? 1 : 0) | (road.elevated ? 2 : 0) | (road.tunnel ? 4 : 0);
    return [road.name, q(road.w), road.dir, road.lanes, flags, flat(rdp(road.pts, 0.65))];
  });

  const bounds = worldBounds(cfg.fullMapBounds, frame);
  const checks = cfg.fullMapLandChecks.map((check) => {
    const [x, z] = frame.toWorld(check.lon, check.lat);
    let distance = Infinity;
    let name = '';
    for (const road of drivable) {
      const next = distanceToRoad(road.pts, x, z);
      if (next < distance) { distance = next; name = road.name || road.cls; }
    }
    if (!(distance <= 2500)) throw new Error(`No drivable OSM road within 2.5 km of ${check.name}`);
    return { name: check.name, distance: Math.round(distance), road: name };
  });

  const roundedBounds = Object.fromEntries(Object.entries(bounds).map(([key, value]) => [key, q(value)]));
  const data = {
    version: 1,
    city: 'hongkong',
    source: {
      ...source,
      bounds: cfg.fullMapBounds,
      note: 'Territory-wide drivable roads. Flat street-level presentation; OSM bridge/tunnel flags are retained, terrain elevation is not imported.'
    },
    bounds: roundedBounds,
    roads
  };
  const output = `// Generated by tools/cities/hongkong/build-full-roads.mjs.\n// © OpenStreetMap contributors, ODbL 1.0. Source: ${data.source.sourceTimestamp} Geofabrik Hong Kong extract.\nexport const HK_FULL_ROADS = ${JSON.stringify(data)};\n`;
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, output);
  const classCounts = {};
  for (const road of drivable) classCounts[road.cls] = (classCounts[road.cls] || 0) + 1;
  const manifest = {
    dataset: data.source.dataset,
    downloadUrl: data.source.downloadUrl,
    sha256: data.source.sha256,
    sourceTimestamp: data.source.sourceTimestamp,
    attribution: data.source.attribution,
    license: data.source.license,
    bounds: cfg.fullMapBounds,
    output: path.relative(process.cwd(), outFile),
    bytes: Buffer.byteLength(output),
    counts: {
      roads: roads.length,
      namedRoads: roads.filter((road) => road[0]).length,
      elevated: drivable.filter((road) => road.elevated).length,
      tunnels: drivable.filter((road) => road.tunnel).length,
      classes: classCounts
    },
    checks
  };
  fs.mkdirSync(path.dirname(manifestFile), { recursive: true });
  fs.writeFileSync(manifestFile, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`[hk-full-roads] ${roads.length} drivable ways, ${manifest.counts.namedRoads} named, ${manifest.counts.elevated} elevated, ${manifest.counts.tunnels} tunnel`);
  console.log(`[hk-full-roads] checks ${checks.map((check) => `${check.name} ${check.distance}m`).join(', ')}`);
  console.log(`[hk-full-roads] ${outFile} (${manifest.bytes} bytes)`);
  return data;
}

function cliValue(flag, fallback) {
  const index = process.argv.indexOf(flag);
  return index >= 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildHongKongFullRoads({
    dataDir: path.resolve(cliValue('--data', DEFAULT_DATA)),
    outFile: path.resolve(cliValue('--out', DEFAULT_OUT)),
    manifestFile: path.resolve(cliValue('--manifest', DEFAULT_MANIFEST))
  });
}
