// Writes a city's GEO module and prints the size of every layer.
import fs from 'node:fs';
import path from 'node:path';

export function emitGeo(GEO, outFile, { title, sources, note = '' }) {
  const json = JSON.stringify(GEO);
  const header = [
    `// ${path.basename(outFile)} — GENERATED by tools/build-city.mjs, do not edit by hand.`,
    `// ${title}`,
    note ? `// ${note}` : null,
    `// 1 unit = 1 m, x = grid east, z = grid south (north = -z), origin at ${GEO.frame.origin.label || 'the city frame origin'}.`,
    `// Polygons & polylines are flat [x0, z0, x1, z1, ...] arrays.`,
    `// Sources: ${sources}`,
    ''
  ].filter(Boolean).join('\n');
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, `${header}\n\nexport const GEO = ${json};\n`);
  console.log(`[emit] wrote ${outFile} (${(fs.statSync(outFile).size / 1024).toFixed(0)} KB)`);
  for (const [key, value] of Object.entries(GEO)) {
    console.log(`  ${key}: ${(JSON.stringify(value).length / 1024).toFixed(0)} KB`);
  }
}
