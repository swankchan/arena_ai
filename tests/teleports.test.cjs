const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { join } = require('node:path');
const test = require('node:test');

const read = (path) => readFileSync(join(__dirname, '..', path), 'utf8');
let TELEPORT_LOCATIONS, LANDMARK_SITES, blockAt, nearestRoads, getIslandBoundsAtZ, TELEPORTS;
test.before(async () => {
  ({ TELEPORT_LOCATIONS, LANDMARK_SITES, blockAt, nearestRoads, getIslandBoundsAtZ } = await import('../js/city-config.js'));
  ({ TELEPORTS } = await import('../js/cities/newyork/meta.js'));
});

test('the New York pack lists every destination on a real roadway inside Manhattan', () => {
  assert.deepEqual(Object.keys(TELEPORT_LOCATIONS).sort(), TELEPORTS.map((point) => point.id).sort());
  for (const point of TELEPORTS) {
    assert.ok(point.name, `${point.id} has a label`);
    assert.ok(Number.isFinite(point.heading), `${point.id} has a heading`);
    assert.equal(point.x, TELEPORT_LOCATIONS[point.id].x);
    assert.equal(point.z, TELEPORT_LOCATIONS[point.id].z);
    assert.equal(blockAt(point.x, point.z), null, `${point.id} lands outside building blocks`);
    const shore = getIslandBoundsAtZ(point.z);
    assert.ok(point.x > shore.westX + 8 && point.x < shore.eastX - 8, `${point.id} stays on the island`);
    const nearby = nearestRoads(point.x, point.z, 20);
    assert.ok(nearby.some(({ road, dist }) => dist < road.w / 2), `${point.id} lands within a street's width`);
  }
});

test('the teleport menu is generated by the city pack, not hardcoded in the page', () => {
  const html = read('index.html');
  assert.equal([...html.matchAll(/data-teleport="/g)].length, 0);
  assert.match(html, /id="teleport-popover"/);
});

test('One World Trade Center arrives on Vesey Street facing the tower', () => {
  const point = TELEPORT_LOCATIONS.owtc;
  const tower = LANDMARK_SITES['One World Trade Center'];
  assert.ok(nearestRoads(point.x, point.z, 20).some(({ road, dist }) => road.name === 'Vesey St' && dist < 1));
  const distance = Math.hypot(tower.x - point.x, tower.z - point.z);
  assert.ok(distance > 100 && distance < 220, 'leave space for the tower view');
  const alignment = ((tower.x - point.x) * Math.sin(point.heading) + (tower.z - point.z) * Math.cos(point.heading)) / distance;
  assert.ok(alignment > 0.999, 'face the tower rather than the neighboring buildings');
});

test('preset and map teleports share arrival resets and mark the resolved landing point', async () => {
  const { createTeleportTo } = await import('../js/teleport.js');
  const calls = [];
  const landed = { x: -305.7, z: 5210 };
  let map = null;
  const teleportTo = createTeleportTo({
    controllerManager: { teleportActiveTo: (...args) => { calls.push(['teleport', ...args]); return landed; } },
    touchControls: { reset: () => calls.push(['touch']) },
    gamepadControls: { reset: () => calls.push(['gamepad']) },
    cameraSystem: { resetForTeleport: () => calls.push(['camera']) },
    selectCamera: (...args) => calls.push(['selectCamera', ...args]),
    getMapSystem: () => map,
    locationLabel: (x, z) => `${x}, ${z}`
  });
  const expected = (args) => [...args, ['touch'], ['gamepad'], ['camera'], ['selectCamera', 'chase', true]];

  // A city without a map (Grid City) still arrives and resets input.
  teleportTo(1, 2, 3);
  assert.deepEqual(calls, expected([['teleport', 1, 2, 3]]));

  map = {};
  for (const point of TELEPORTS) {
    calls.length = 0;
    teleportTo(point.x, point.z, point.heading);
    assert.deepEqual(calls, expected([['teleport', point.x, point.z, point.heading]]));
    assert.equal(map.waypoint.x, landed.x);
    assert.equal(map.waypoint.z, landed.z);
    assert.equal(map.waypoint.name, `${landed.x}, ${landed.z}`);
  }

  calls.length = 0;
  teleportTo(100, 200);
  assert.deepEqual(calls[0], ['teleport', 100, 200, Math.PI], 'heading defaults to PI');
});
